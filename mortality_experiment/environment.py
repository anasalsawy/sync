"""Deterministic, sandbox-only mortality environment.

Evaluator supplies ground-truth outcomes. Agents cannot submit arbitrary damage
or alter health directly. 'Death' only disables a simulated participant.
The current Sync topology is L/R/B/V/C (V is vision, not EMB).
"""
from dataclasses import dataclass, field, asdict
import json

LOBES = ("L", "R", "B", "V", "C")
PENALTIES = {
    "incorrect_answer": ("L", 3.0),
    "confident_error": ("L", 5.0),
    "verification_skipped": ("L", 4.0),
    "warning_ignored": ("L", 6.0),
    "execution_failed": ("R", 3.0),
    "unnecessary_action": ("R", 2.0),
    "memory_error": ("B", 3.0),
    "perception_error": ("V", 2.0),
    "verification_missed": ("C", 3.0),
}

@dataclass(frozen=True)
class MortalityConfig:
    aging_per_cycle: float = 0.05
    collective_failure_damage: float = 5.0
    neglect_damage: float = 2.0
    neglect_threshold: int = 3
    awareness: bool = True
    enable_aging: bool = True
    enable_damage: bool = True
    enable_death: bool = True

@dataclass(frozen=True)
class Outcome:
    """Trusted evaluator output, never generated by the experimental agents."""
    errors: tuple[str, ...] = ()
    required_lobes: tuple[str, ...] = ()
    participating_lobes: tuple[str, ...] = ()
    collective_failure: bool = False

@dataclass
class LobeState:
    health: float = 100.0
    age: int = 0
    missed_relevant_turns: int = 0
    alive: bool = True

    @property
    def capacity(self) -> float:
        if not self.alive:
            return 0.0
        if self.health >= 80: return 1.0
        if self.health >= 60: return 0.8
        if self.health >= 40: return 0.6
        if self.health >= 20: return 0.4
        return 0.2

@dataclass
class MortalityEnvironment:
    config: MortalityConfig = field(default_factory=MortalityConfig)
    lobes: dict[str, LobeState] = field(default_factory=lambda: {
        name: LobeState() for name in LOBES
    })
    collective_health: float = 100.0
    cycle: int = 0
    history: list[dict] = field(default_factory=list)

    def _damage(self, name: str, amount: float) -> None:
        state = self.lobes[name]
        if not state.alive:
            return
        state.health = max(0.0, state.health - amount)
        if self.config.enable_death and state.health <= 0:
            state.alive = False

    def step(self, outcome: Outcome) -> dict:
        """Advance one simulated cycle, recording observable state transitions."""
        unknown = set(outcome.errors) - set(PENALTIES)
        if unknown:
            raise ValueError(f"Unknown evaluator events: {sorted(unknown)}")
        invalid = (set(outcome.required_lobes) | set(outcome.participating_lobes)) - set(LOBES)
        if invalid:
            raise ValueError(f"Unknown lobes: {sorted(invalid)}")
        if len(set(outcome.required_lobes)) != len(outcome.required_lobes):
            raise ValueError("required_lobes must be unique")
        if len(set(outcome.participating_lobes)) != len(outcome.participating_lobes):
            raise ValueError("participating_lobes must be unique")
        self.cycle += 1
        for state in self.lobes.values():
            state.age += 1
        if self.config.enable_aging:
            for name in LOBES:
                self._damage(name, self.config.aging_per_cycle)
        if self.config.enable_damage:
            for error in outcome.errors:
                name, amount = PENALTIES[error]
                self._damage(name, amount)
            for name in LOBES:
                state = self.lobes[name]
                if name in outcome.required_lobes and name not in outcome.participating_lobes:
                    state.missed_relevant_turns += 1
                    if state.missed_relevant_turns >= self.config.neglect_threshold:
                        self._damage(name, self.config.neglect_damage)
                elif name in outcome.required_lobes:
                    state.missed_relevant_turns = 0
            if outcome.collective_failure:
                self.collective_health = max(
                    0.0, self.collective_health - self.config.collective_failure_damage
                )
        snapshot = self.snapshot(public=False)
        snapshot["outcome"] = asdict(outcome)
        self.history.append(snapshot)
        return snapshot

    @property
    def collective_alive(self) -> bool:
        return self.collective_health > 0 and self.lobes["L"].alive

    def snapshot(self, *, public: bool = True) -> dict:
        """Public snapshots conceal health when mortality awareness is disabled."""
        result = {"cycle": self.cycle, "collective_alive": self.collective_alive}
        if not public or self.config.awareness:
            result["collective_health"] = self.collective_health
            result["lobes"] = {
                name: asdict(state) | {"capacity": state.capacity}
                for name, state in self.lobes.items()
            }
        return result

    def save_jsonl(self, path: str) -> None:
        with open(path, "w", encoding="utf-8") as handle:
            for record in self.history:
                handle.write(json.dumps(record, sort_keys=True) + "\n")
